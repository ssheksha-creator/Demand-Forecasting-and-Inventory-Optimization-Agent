def get_stockout_timeline(
    store_id,
    product_id,
    recommendations: Optional[pd.DataFrame] = None,
    horizon: int = DEFAULT_HORIZON,
    forecasts: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """
    Return a daily inventory projection for a selected
    Store × Product pair.

    Useful for the Inventory Risk and Product Detail pages.
    """

    if recommendations is None:
        recommendations = (
            calculate_inventory_recommendations(
                horizon=horizon
            )
        )

    if forecasts is None:
        forecasts = _load_forecasts(
            horizon=horizon
        )

    rec = recommendations[
        (recommendations["Store ID"] == store_id)
        & (recommendations["Product ID"] == product_id)
    ]

    if rec.empty:
        return pd.DataFrame()

    rec = rec.iloc[0]

    forecast_window = _prepare_forecast_window(
        forecasts,
        horizon=horizon,
    )

    daily = forecast_window[
        (forecast_window["Store ID"] == store_id)
        & (forecast_window["Product ID"] == product_id)
    ].copy()

    if daily.empty:
        return pd.DataFrame()

    daily = daily.sort_values("Date").head(horizon)

    starting_inventory = float(
        rec["Current Inventory"]
    )

    remaining = starting_inventory

    rows = []

    for _, row in daily.iterrows():

        p50 = max(
            float(row["P50 Demand"]),
            0,
        )

        p90 = max(
            float(row["P90 Demand"]),
            p50,
        )

        remaining -= p50

        rows.append(
            {
                "Date": row["Date"],
                "Store ID": store_id,
                "Product ID": product_id,
                "P50 Demand": round(p50, 2),
                "P90 Demand": round(p90, 2),
                "Projected Inventory": round(
                    max(remaining, 0),
                    2,
                ),
                "Reorder Point": rec[
                    "Reorder Point"
                ],
                "Stockout": remaining <= 0,
            }
        )

    return pd.DataFrame(rows)


# ============================================================
# SAVE OUTPUT
# ============================================================

def save_inventory_recommendations(
    recommendations: Optional[pd.DataFrame] = None,
) -> Path:
    """
    Save recommendations to outputs/recommendations_v2.csv.
    """

    if recommendations is None:
        recommendations = (
            calculate_inventory_recommendations()
        )

    OUTPUT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    recommendations.to_csv(
        OUTPUT_PATH,
        index=False,
    )

    return OUTPUT_PATH


