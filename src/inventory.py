# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path(__file__).resolve().parent.parent

FORECAST_PATH = BASE_DIR / "outputs" / "forecasts_v2.csv"
OUTPUT_PATH = BASE_DIR / "outputs" / "recommendations_v2.csv"

DEFAULT_LEAD_TIME_DAYS = 3
DEFAULT_SERVICE_LEVEL = 0.95
DEFAULT_HORIZON = 7

# Normal-distribution z-value for 95% service level.
SERVICE_LEVEL_Z = 1.645


# ============================================================
# DATA LOADING
# ============================================================

def _load_forecasts(
    horizon: int = DEFAULT_HORIZON,
) -> pd.DataFrame:
    """
    Load V2 forecast output.

    Expected columns:
        Date
        Store ID
        Product ID
        Predicted Demand
        P10 Demand
        P50 Demand
        P90 Demand
    """

    if FORECAST_PATH.exists():
        forecasts = pd.read_csv(FORECAST_PATH)

        forecasts["Date"] = pd.to_datetime(forecasts["Date"])

        # Keep future forecast rows when available.
        if "Forecast Type" in forecasts.columns:
            future = forecasts[
                forecasts["Forecast Type"]
                .astype(str)
                .str.lower()
                .eq("future")
            ].copy()

            if not future.empty:
                forecasts = future

        required = [
            "Date",
            "Store ID",
            "Product ID",
            "Predicted Demand",
        ]

        missing = [c for c in required if c not in forecasts.columns]

        if missing:
            raise ValueError(
                f"Forecast file is missing required columns: {missing}"
            )

        # Backward-compatible fallback.
        if "P50 Demand" not in forecasts.columns:
            forecasts["P50 Demand"] = forecasts["Predicted Demand"]

        if "P10 Demand" not in forecasts.columns:
            forecasts["P10 Demand"] = forecasts["P50 Demand"]

        if "P90 Demand" not in forecasts.columns:
            forecasts["P90 Demand"] = forecasts["P50 Demand"]

        forecasts["P10 Demand"] = pd.to_numeric(
            forecasts["P10 Demand"],
            errors="coerce",
        ).clip(lower=0)

        forecasts["P50 Demand"] = pd.to_numeric(
            forecasts["P50 Demand"],
            errors="coerce",
        ).clip(lower=0)

        forecasts["P90 Demand"] = pd.to_numeric(
            forecasts["P90 Demand"],
            errors="coerce",
        ).clip(lower=0)

        forecasts = forecasts.sort_values(
            ["Store ID", "Product ID", "Date"]
        )

        return forecasts

    # If forecast file does not exist, generate it.
    try:
        from forecasting import forecast_all_products

        forecasts = forecast_all_products(horizon=horizon)

        forecasts["Date"] = pd.to_datetime(forecasts["Date"])

        return forecasts

    except Exception as exc:
        raise FileNotFoundError(
            "V2 forecast output was not found and future forecasts "
            f"could not be generated.\nExpected: {FORECAST_PATH}\n"
            f"Original error: {exc}"
        )


