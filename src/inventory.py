# ============================================================
# STORE ANALYTICS
# ============================================================

def get_store_inventory_analytics(
    recommendations: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """
    Aggregate inventory optimization results by store.
    """

    if recommendations is None:
        recommendations = (
            calculate_inventory_recommendations()
        )

    df = recommendations.copy()

    grouped = (
        df.groupby("Store ID")
        .agg(
            Current_Inventory=(
                "Current Inventory",
                "sum",
            ),

            Forecast_P50_Demand=(
                "Forecast P50 Demand",
                "sum",
            ),

            Forecast_P90_Demand=(
                "Forecast P90 Demand",
                "sum",
            ),

            Recommended_Order=(
                "Recommended Order",
                "sum",
            ),

            Projected_Shortage=(
                "Projected Shortage",
                "sum",
            ),

            High_Risk=(
                "Risk Level",
                lambda x: int(
                    (x == "High").sum()
                ),
            ),

            Medium_Risk=(
                "Risk Level",
                lambda x: int(
                    (x == "Medium").sum()
                ),
            ),

            Low_Risk=(
                "Risk Level",
                lambda x: int(
                    (x == "Low").sum()
                ),
            ),

            Average_Stockout_Risk=(
                "Stockout Risk",
                "mean",
            ),
        )
        .reset_index()
    )

    grouped["Inventory Coverage Days"] = (
        grouped["Current_Inventory"]
        / grouped["Forecast_P50_Demand"]
        * DEFAULT_HORIZON
    ).replace(
        [np.inf, -np.inf],
        np.nan,
    )

    grouped = grouped.sort_values(
        "Average_Stockout_Risk",
        ascending=False,
    )

    return grouped.reset_index(drop=True)


