def get_business_summary(
    data: Optional[pd.DataFrame] = None,
    recommendations: Optional[pd.DataFrame] = None,
) -> Dict[str, float]:
    """Return current inventory and forecast risk summary."""

    df = _ensure_data(data)

    if recommendations is None:
        recommendations = _load_recommendations()

    summary: Dict[str, float] = {
        "total_inventory": 0.0,
        "forecast_demand_p50": 0.0,
        "forecast_demand_p90": 0.0,
        "high_risk": 0,
        "medium_risk": 0,
        "low_risk": 0,
        "recommended_units": 0,
        "projected_shortage": 0.0,
        "average_daily_demand": 0.0,
        "stockout_risk_count": 0,
        "average_stockout_risk": 0.0,
    }

    if "Demand" in df.columns and not df.empty:
        summary["average_daily_demand"] = float(
            df["Demand"].mean()
        )

    if recommendations is None or recommendations.empty:
        return summary

    def col_sum(name: str) -> float:
        if name not in recommendations.columns:
            return 0.0
        return float(
            pd.to_numeric(
                recommendations[name],
                errors="coerce",
            ).fillna(0).sum()
        )

    summary["total_inventory"] = col_sum(
        "Current Inventory"
    )

    summary["forecast_demand_p50"] = col_sum(
        "Forecast P50 Demand"
    )

    summary["forecast_demand_p90"] = col_sum(
        "Forecast P90 Demand"
    )

    summary["recommended_units"] = int(
        round(col_sum("Recommended Order"))
    )

    summary["projected_shortage"] = col_sum(
        "Projected Shortage"
    )

    if "Risk Level" in recommendations.columns:
        risk = recommendations["Risk Level"].astype(str)

        summary["high_risk"] = int(
            (risk == "High").sum()
        )
        summary["medium_risk"] = int(
            (risk == "Medium").sum()
        )
        summary["low_risk"] = int(
            (risk == "Low").sum()
        )

    if "Stockout Risk" in recommendations.columns:
        stockout = pd.to_numeric(
            recommendations["Stockout Risk"],
            errors="coerce",
        )

        summary["stockout_risk_count"] = int(
            (stockout >= 70).sum()
        )

        summary["average_stockout_risk"] = float(
            stockout.mean()
        )

    return summary


