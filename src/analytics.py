def get_dataset_overview(
    data: Optional[pd.DataFrame] = None,
) -> Dict[str, Any]:
    """Return high-level dataset information."""

    df = _ensure_data(data)

    return {
        "rows": int(len(df)),
        "columns": int(len(df.columns)),
        "date_min": (
            df["Date"].min().strftime("%Y-%m-%d")
            if "Date" in df.columns and not df.empty
            else None
        ),
        "date_max": (
            df["Date"].max().strftime("%Y-%m-%d")
            if "Date" in df.columns and not df.empty
            else None
        ),
        "stores": int(df["Store ID"].nunique())
        if "Store ID" in df.columns else 0,
        "products": int(df["Product ID"].nunique())
        if "Product ID" in df.columns else 0,
        "categories": int(df["Category"].nunique())
        if "Category" in df.columns else 0,
        "regions": int(df["Region"].nunique())
        if "Region" in df.columns else 0,
        "weather_conditions": int(
            df["Weather Condition"].nunique()
        )
        if "Weather Condition" in df.columns else 0,
        "missing_values": int(df.isna().sum().sum()),
    }


