def get_category_analytics(
    data: Optional[pd.DataFrame] = None,
    recommendations: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """
    Category-level demand and inventory analysis.

    IMPORTANT:
    Category is assigned at the Store×Product level using the
    latest observed historical category.

    This prevents recommendation rows from being duplicated when
    a Product ID has appeared under more than one category.
    """

    df = _ensure_data(data)

    if recommendations is None:
        recommendations = _load_recommendations()

    # Historical category metrics.
    historical = (
        df.groupby("Category")
        .agg(
            Historical_Demand=("Demand", "sum"),
            Average_Demand=("Demand", "mean"),
            Average_Inventory=(
                "Inventory Level",
                "mean",
            ),
            Average_Price=("Price", "mean"),
            Average_Discount=("Discount", "mean"),
        )
        .reset_index()
    )

    if recommendations is None or recommendations.empty:
        return historical

    # --------------------------------------------------------------
    # CRITICAL FIX:
    # Determine exactly ONE category for each Store×Product series.
    # The latest historical record represents the current mapping.
    # --------------------------------------------------------------

    latest_series = (
        df.sort_values("Date")
        .groupby(
            ["Store ID", "Product ID"],
            as_index=False,
        )
        .tail(1)
        [
            [
                "Store ID",
                "Product ID",
                "Category",
            ]
        ]
        .copy()
    )

    # Remove an existing Category column before merge.
    # Otherwise pandas creates Category_x / Category_y.
    rec = recommendations.drop(
        columns=["Category"],
        errors="ignore",
    ).copy()

    rec = rec.merge(
        latest_series,
        on=["Store ID", "Product ID"],
        how="left",
    )

    # Fail loudly if a recommendation cannot be categorized.
    if rec["Category"].isna().any():
        missing_count = int(
            rec["Category"].isna().sum()
        )
        raise ValueError(
            "Category mapping failed for "
            f"{missing_count} recommendation rows."
        )

    # Numeric safety.
    numeric_columns = [
        "Current Inventory",
        "Forecast P50 Demand",
        "Forecast P90 Demand",
        "Recommended Order",
        "Projected Shortage",
        "Stockout Risk",
    ]

    for column in numeric_columns:
        if column in rec.columns:
            rec[column] = pd.to_numeric(
                rec[column],
                errors="coerce",
            )

    category_inventory = (
        rec.groupby("Category")
        .agg(
            Current_Inventory=(
                "Current Inventory",
                "sum",
            ),
            Forecast_P50_Demand=(
                "Forecast P50 Demand",
                "sum",
            ),
            Forecast_P90_Demand=(
                "Forecast P90 Demand",
                "sum",
            ),
            Recommended_Order=(
                "Recommended Order",
                "sum",
            ),
            Projected_Shortage=(
                "Projected Shortage",
                "sum",
            ),
            High_Risk=(
                "Risk Level",
                lambda x: int((x == "High").sum()),
            ),
            Medium_Risk=(
                "Risk Level",
                lambda x: int((x == "Medium").sum()),
            ),
            Low_Risk=(
                "Risk Level",
                lambda x: int((x == "Low").sum()),
            ),
            Average_Stockout_Risk=(
                "Stockout Risk",
                "mean",
            ),
        )
        .reset_index()
    )

    result = historical.merge(
        category_inventory,
        on="Category",
        how="left",
    )

    result["Forecast_to_Inventory_Ratio"] = (
        result["Forecast_P50_Demand"]
        / result["Current_Inventory"].replace(
            0,
            np.nan,
        )
    )

    result["Inventory_Coverage_Days"] = (
        result["Current_Inventory"]
        / (
            result["Forecast_P50_Demand"] / 7
        ).replace(
            0,
            np.nan,
        )
    )

    return result.sort_values(
        "Forecast_P50_Demand",
        ascending=False,
    ).reset_index(drop=True)


