"""
Analytics V2
============

Descriptive, comparative, inventory and model-performance analytics
for the AI Demand & Inventory Optimizer.

Uses ONLY the project's sales_data.csv and generated V2 outputs.

Important:
- Category analytics assigns one category per Store×Product series
  using the latest historical observation.
- This prevents duplicate recommendation rows when category values
  vary across historical records.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Dict, Optional

import numpy as np
import pandas as pd


# ---------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------

ROOT_DIR = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT_DIR / "sales_data.csv"
FORECAST_PATH = ROOT_DIR / "outputs" / "forecasts_v2.csv"
RECOMMENDATION_PATH = ROOT_DIR / "outputs" / "recommendations_v2.csv"
METADATA_PATH = ROOT_DIR / "models" / "model_metadata_v2.json"
ROLLING_VALIDATION_PATH = ROOT_DIR / "outputs" / "rolling_validation_v2.csv"
VALIDATION_PREDICTIONS_PATH = ROOT_DIR / "outputs" / "validation_predictions_v2.csv"


# ---------------------------------------------------------------------
# Data loading helpers
# ---------------------------------------------------------------------

def load_data(path: Optional[str | Path] = None) -> pd.DataFrame:
    """Load the historical sales dataset."""
    csv_path = Path(path) if path else DATA_PATH

    if not csv_path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {csv_path}"
        )

    df = pd.read_csv(csv_path)

    if "Date" in df.columns:
        df["Date"] = pd.to_datetime(df["Date"])

    return df


def _ensure_data(
    data: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """Return a safe copy of the supplied or default dataset."""
    if data is None:
        return load_data()

    result = data.copy()

    if "Date" in result.columns:
        result["Date"] = pd.to_datetime(result["Date"])

    return result


def _load_recommendations() -> pd.DataFrame:
    """Load inventory recommendations generated by inventory.py."""
    if not RECOMMENDATION_PATH.exists():
        return pd.DataFrame()

    return pd.read_csv(RECOMMENDATION_PATH)


def _load_forecasts() -> pd.DataFrame:
    """Load generated V2 forecasts."""
    if not FORECAST_PATH.exists():
        return pd.DataFrame()

    df = pd.read_csv(FORECAST_PATH)

    if "Date" in df.columns:
        df["Date"] = pd.to_datetime(df["Date"])

    return df


