def get_monthly_demand(
    data: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """Return monthly demand trend."""

    df = _ensure_data(data)

    df["Year"] = df["Date"].dt.year
    df["Month"] = df["Date"].dt.month
    df["Month_Name"] = df["Date"].dt.strftime("%b")

    result = (
        df.groupby(
            [
                "Year",
                "Month",
                "Month_Name",
            ],
            as_index=False,
        )
        .agg(
            Demand=("Demand", "sum"),
            Average_Demand=("Demand", "mean"),
        )
        .sort_values(
            ["Year", "Month"]
        )
    )

    return result


