def get_store_analytics(
    data: Optional[pd.DataFrame] = None,
    recommendations: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """Return historical + forecast + inventory analytics by store."""

    df = _ensure_data(data)

    if recommendations is None:
        recommendations = _load_recommendations()

    historical = (
        df.groupby("Store ID")
        .agg(
            Historical_Demand=("Demand", "sum"),
            Average_Daily_Demand=("Demand", "mean"),
            Average_Inventory=("Inventory Level", "mean"),
            Latest_Inventory=("Inventory Level", "last"),
            Average_Price=("Price", "mean"),
            Average_Discount=("Discount", "mean"),
        )
        .reset_index()
    )

    if recommendations.empty:
        return historical

    numeric_columns = [
        "Current Inventory",
        "Forecast P50 Demand",
        "Forecast P90 Demand",
        "Recommended Order",
        "Projected Shortage",
        "Stockout Risk",
    ]

    for column in numeric_columns:
        if column in recommendations.columns:
            recommendations[column] = pd.to_numeric(
                recommendations[column],
                errors="coerce",
            )

    grouped = (
        recommendations.groupby("Store ID")
        .agg(
            Current_Inventory=("Current Inventory", "sum"),
            Forecast_P50_Demand=(
                "Forecast P50 Demand",
                "sum",
            ),
            Forecast_P90_Demand=(
                "Forecast P90 Demand",
                "sum",
            ),
            Recommended_Order=(
                "Recommended Order",
                "sum",
            ),
            Projected_Shortage=(
                "Projected Shortage",
                "sum",
            ),
            High_Risk=(
                "Risk Level",
                lambda x: int((x == "High").sum()),
            ),
            Medium_Risk=(
                "Risk Level",
                lambda x: int((x == "Medium").sum()),
            ),
            Low_Risk=(
                "Risk Level",
                lambda x: int((x == "Low").sum()),
            ),
            Average_Stockout_Risk=(
                "Stockout Risk",
                "mean",
            ),
        )
        .reset_index()
    )

    result = historical.merge(
        grouped,
        on="Store ID",
        how="left",
    )

    result["Forecast_to_Inventory_Ratio"] = (
        result["Forecast_P50_Demand"]
        / result["Current_Inventory"].replace(0, np.nan)
    )

    result["Inventory_Coverage_Days"] = (
        result["Current_Inventory"]
        / (
            result["Forecast_P50_Demand"] / 7
        ).replace(0, np.nan)
    )

    return result.sort_values(
        "Forecast_P50_Demand",
        ascending=False,
    ).reset_index(drop=True)


