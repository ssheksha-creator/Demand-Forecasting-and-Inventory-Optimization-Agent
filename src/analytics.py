def get_risk_distribution(
    df: Optional[pd.DataFrame] = None,
    recommendations: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """
    Return inventory risk distribution in a consistent format.

    Accepts either the raw sales dataframe or an already generated
    recommendations dataframe. Uses outputs/recommendations_v2.csv
    when the raw sales dataframe is supplied.
    """

    # app.py normally passes the raw sales dataframe.
    if recommendations is None:
        recommendations = df

    # Raw sales data does not contain risk columns, so use the
    # recommendations already generated by Phase 3.
    if recommendations is None:
        recommendations = _load_recommendations()
    elif not any(
        col in recommendations.columns
        for col in ("Risk Level", "Stockout Risk", "Risk Score")
    ):
        generated = _load_recommendations()
        recommendations = generated if not generated.empty else pd.DataFrame()

    if recommendations.empty:
        return pd.DataFrame(
            columns=["Risk Level", "Count"]
        )

    # Current V2 schema.
    if "Risk Level" in recommendations.columns:
        risk_series = recommendations["Risk Level"]

    # Compatibility with older/current variants.
    elif "Stockout Risk" in recommendations.columns:
        risk_score = pd.to_numeric(
            recommendations["Stockout Risk"],
            errors="coerce"
        ).fillna(0)

        risk_series = pd.cut(
            risk_score,
            bins=[-float("inf"), 35, 70, float("inf")],
            labels=["Low", "Medium", "High"]
        )

    elif "Risk Score" in recommendations.columns:
        risk_score = pd.to_numeric(
            recommendations["Risk Score"],
            errors="coerce"
        ).fillna(0)

        risk_series = pd.cut(
            risk_score,
            bins=[-float("inf"), 35, 70, float("inf")],
            labels=["Low", "Medium", "High"]
        )

    elif "Days Until Stockout" in recommendations.columns:
        days = pd.to_numeric(
            recommendations["Days Until Stockout"],
            errors="coerce"
        ).fillna(999)

        risk_series = pd.cut(
            days,
            bins=[-float("inf"), 3, 7, float("inf")],
            labels=["High", "Medium", "Low"]
        )

    else:
        return pd.DataFrame({
            "Risk Level": ["High", "Medium", "Low"],
            "Count": [0, 0, 0]
        })

    return (
        pd.Series(risk_series)
        .value_counts()
        .reindex(["High", "Medium", "Low"], fill_value=0)
        .rename_axis("Risk Level")
        .reset_index(name="Count")
    )


def get_top_risk_products(
    recommendations: Optional[pd.DataFrame] = None,
    n: int = 10,
) -> pd.DataFrame:
    """Return the highest-risk Store×Product recommendations."""

    if recommendations is None:
        recommendations = _load_recommendations()

    if recommendations.empty:
        return pd.DataFrame()

    result = recommendations.copy()

    sort_columns = [
        column
        for column in [
            "Stockout Risk",
            "Days Until Stockout",
            "Projected Shortage",
        ]
        if column in result.columns
    ]

    ascending = [
        False,
        True,
        False,
    ][: len(sort_columns)]

    if sort_columns:
        result = result.sort_values(
            sort_columns,
            ascending=ascending,
        )

    return result.head(n).reset_index(drop=True)


