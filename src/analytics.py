def _recursive_find(
    obj: Any,
    target_keys: set[str],
) -> Dict[str, Any]:
    """Find matching dictionary keys recursively."""

    if isinstance(obj, dict):
        for key, value in obj.items():
            if str(key).lower() in target_keys:
                if isinstance(value, dict):
                    return value
                return {"value": value}

        for value in obj.values():
            found = _recursive_find(
                value,
                target_keys,
            )
            if found:
                return found

    elif isinstance(obj, list):
        for item in obj:
            found = _recursive_find(
                item,
                target_keys,
            )
            if found:
                return found

    return {}


def _read_metadata() -> Dict[str, Any]:
    """Read model metadata safely."""
    if not METADATA_PATH.exists():
        return {}

    try:
        with open(
            METADATA_PATH,
            "r",
            encoding="utf-8",
        ) as file:
            return json.load(file)
    except Exception:
        return {}


def get_model_performance() -> Dict[str, Any]:
    """
    Return model-performance information.

    Supports multiple metadata layouts and falls back to the
    generated validation CSV when necessary.
    """

    metadata = _read_metadata()

    result: Dict[str, Any] = {
        "available": False,
        "metrics": {},
        "baseline_metrics": {},
        "feature_importance": pd.DataFrame(),
        "rolling_validation": pd.DataFrame(),
    }

    # --------------------------------------------------------------
    # Extract metrics from metadata using several possible names.
    # --------------------------------------------------------------

    metrics = _recursive_find(
        metadata,
        {
            "metrics",
            "validation_metrics",
            "holdout_metrics",
            "model_metrics",
        },
    )

    baseline = _recursive_find(
        metadata,
        {
            "baseline_metrics",
            "baseline",
            "benchmark_metrics",
        },
    )

    if metrics:
        if "value" in metrics and isinstance(
            metrics["value"],
            dict,
        ):
            result["metrics"] = metrics["value"]
        else:
            result["metrics"] = metrics

    if baseline:
        if "value" in baseline and isinstance(
            baseline["value"],
            dict,
        ):
            result["baseline_metrics"] = baseline["value"]
        else:
            result["baseline_metrics"] = baseline

    # --------------------------------------------------------------
    # Feature importance.
    # --------------------------------------------------------------

    importance = _recursive_find(
        metadata,
        {
            "feature_importance",
            "feature_importances",
        },
    )

    if importance:
        if "value" in importance:
            importance = importance["value"]

        if isinstance(importance, dict):
            result["feature_importance"] = (
                pd.DataFrame(
                    {
                        "Feature": list(
                            importance.keys()
                        ),
                        "Importance": list(
                            importance.values()
                        ),
                    }
                )
            )

        elif isinstance(importance, list):
            rows = []

            for item in importance:
                if isinstance(item, dict):
                    feature = (
                        item.get("Feature")
                        or item.get("feature")
                        or item.get("name")
                    )

                    value = (
                        item.get("Importance")
                        or item.get("importance")
                        or item.get("value")
                    )

                    if feature is not None:
                        rows.append(
                            {
                                "Feature": feature,
                                "Importance": value,
                            }
                        )

            if rows:
                result["feature_importance"] = (
                    pd.DataFrame(rows)
                )

    # --------------------------------------------------------------
    # Rolling validation CSV fallback.
    # --------------------------------------------------------------

    if ROLLING_VALIDATION_PATH.exists():
        try:
            rolling = pd.read_csv(
                ROLLING_VALIDATION_PATH
            )
            result["rolling_validation"] = rolling

            if not rolling.empty:
                result["available"] = True

                # If metadata metrics are missing, derive the
                # LightGBM V2 aggregate from rolling validation.
                if not result["metrics"]:
                    model_column = None

                    for candidate in [
                        "Model",
                        "model",
                        "Algorithm",
                    ]:
                        if candidate in rolling.columns:
                            model_column = candidate
                            break

                    if model_column:
                        mask = rolling[
                            model_column
                        ].astype(str).str.contains(
                            "LightGBM",
                            case=False,
                            na=False,
                        )

                        model_rows = rolling.loc[
                            mask
                        ]

                        if not model_rows.empty:
                            row = model_rows.iloc[0]

                            result["metrics"] = {
                                key: float(row[key])
                                for key in [
                                    "MAE",
                                    "RMSE",
                                    "MAPE",
                                ]
                                if key in row.index
                            }

        except Exception:
            pass

    # --------------------------------------------------------------
    # Validation prediction fallback.
    # --------------------------------------------------------------

    if VALIDATION_PREDICTIONS_PATH.exists():
        try:
            validation = pd.read_csv(
                VALIDATION_PREDICTIONS_PATH
            )

            actual_col = next(
                (
                    c for c in validation.columns
                    if c.lower()
                    in {
                        "actual demand",
                        "actual_demand",
                        "actual",
                    }
                ),
                None,
            )

            predicted_col = next(
                (
                    c for c in validation.columns
                    if c.lower()
                    in {
                        "predicted demand",
                        "predicted_demand",
                        "prediction",
                        "predicted",
                    }
                ),
                None,
            )

            if (
                actual_col
                and predicted_col
                and not result["metrics"]
            ):
                actual = pd.to_numeric(
                    validation[actual_col],
                    errors="coerce",
                )

                predicted = pd.to_numeric(
                    validation[predicted_col],
                    errors="coerce",
                )

                mask = (
                    actual.notna()
                    & predicted.notna()
                )

                actual = actual[mask]
                predicted = predicted[mask]

                if len(actual):
                    errors = actual - predicted

                    mae = float(
                        errors.abs().mean()
                    )

                    rmse = float(
                        np.sqrt(
                            np.mean(
                                errors ** 2
                            )
                        )
                    )

                    nonzero = actual != 0

                    mape = float(
                        (
                            (
                                errors[nonzero].abs()
                                / actual[nonzero].abs()
                            )
                            .mean()
                            * 100
                        )
                    ) if nonzero.any() else math.nan

                    result["metrics"] = {
                        "MAE": mae,
                        "RMSE": rmse,
                        "MAPE": mape,
                    }

                    result["available"] = True

        except Exception:
            pass

    if result["metrics"]:
        result["available"] = True

    return result


